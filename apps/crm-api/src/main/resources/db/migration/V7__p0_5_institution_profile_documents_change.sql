-- P0-5 机构合同、资质及敏感变更审批。file_id 仅为外部文件引用，本迁移不依赖文件表。
CREATE TABLE IF NOT EXISTS `crm_institution_contract` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '企业/租户隔离',
  `institution_id` BIGINT UNSIGNED NOT NULL COMMENT '机构',
  `contract_no` VARCHAR(96) NOT NULL COMMENT '合同编号，同一编号多版本',
  `version_no` INT NOT NULL COMMENT '合同版本号',
  `title` VARCHAR(192) NOT NULL COMMENT '合同标题',
  `contract_type` VARCHAR(64) NOT NULL COMMENT '合同类型',
  `start_date` DATE NOT NULL COMMENT '合同开始日期',
  `end_date` DATE NULL COMMENT '合同结束日期',
  `file_id` BIGINT UNSIGNED NOT NULL COMMENT '本版本文件引用，非外键',
  `amount_fen` BIGINT NULL COMMENT '合同金额，整数分',
  `notes` VARCHAR(1000) NULL COMMENT '备注',
  `status` VARCHAR(32) NOT NULL COMMENT 'PENDING_REVIEW/ACTIVE/SUPERSEDED/REJECTED',
  `previous_contract_id` BIGINT UNSIGNED NULL COMMENT '上一版本合同',
  `created_by` BIGINT UNSIGNED NOT NULL COMMENT '创建人',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，UTC',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_institution_contract_1` (`tenant_id`,`contract_no`,`version_no`),
  KEY `idx_institution_contract_1` (`tenant_id`,`institution_id`,`status`,`id`),
  CONSTRAINT `fk_institution_contract_institution` FOREIGN KEY (`institution_id`) REFERENCES `crm_institution` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='机构合同版本历史，不覆盖旧文件';

CREATE TABLE IF NOT EXISTS `crm_institution_qualification` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '企业/租户隔离',
  `institution_id` BIGINT UNSIGNED NOT NULL COMMENT '机构',
  `qualification_type` VARCHAR(64) NOT NULL COMMENT '资质类型',
  `title` VARCHAR(192) NOT NULL COMMENT '资质名称',
  `license_no_cipher` VARCHAR(512) NULL COMMENT '资质编号密文',
  `file_id` BIGINT UNSIGNED NOT NULL COMMENT '扫描件引用，非外键',
  `valid_from` DATE NULL COMMENT '有效期起',
  `valid_to` DATE NULL COMMENT '有效期止',
  `status` VARCHAR(32) NOT NULL COMMENT 'PENDING_REVIEW/APPROVED/REJECTED',
  `created_by` BIGINT UNSIGNED NOT NULL COMMENT '创建人',
  `reviewed_by` BIGINT UNSIGNED NULL COMMENT '审核人',
  `reviewed_at` DATETIME(3) NULL COMMENT '审核时间，UTC',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，UTC',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (`id`),
  KEY `idx_institution_qualification_1` (`tenant_id`,`institution_id`,`status`,`valid_to`),
  CONSTRAINT `fk_institution_qualification_institution` FOREIGN KEY (`institution_id`) REFERENCES `crm_institution` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='机构资质与审核状态';

CREATE TABLE IF NOT EXISTS `crm_profile_change_request` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '企业/租户隔离',
  `institution_id` BIGINT UNSIGNED NOT NULL COMMENT '机构',
  `change_type` VARCHAR(48) NOT NULL COMMENT 'ONBOARDING/PROFILE_FIELD/CONTRACT_ACTIVATION/QUALIFICATION_REVIEW',
  `field_code` VARCHAR(64) NULL COMMENT '受限字段编码',
  `target_id` BIGINT UNSIGNED NOT NULL COMMENT '变更目标ID',
  `base_version` BIGINT UNSIGNED NOT NULL COMMENT '申请时机构版本',
  `target_version` BIGINT UNSIGNED NOT NULL COMMENT '申请时目标版本',
  `before_cipher` TEXT NULL COMMENT '原值密文',
  `after_cipher` TEXT NULL COMMENT '新值密文',
  `before_masked` TEXT NULL COMMENT '原值脱敏JSON',
  `after_masked` TEXT NULL COMMENT '新值脱敏JSON',
  `reason` VARCHAR(1000) NOT NULL COMMENT '申请理由',
  `evidence_file_id` BIGINT UNSIGNED NULL COMMENT '证据文件引用，非外键',
  `status` VARCHAR(48) NOT NULL COMMENT 'PENDING_REVIEW/APPROVED/REJECTED/CONFLICT_REVALIDATE',
  `current_step` VARCHAR(32) NOT NULL COMMENT 'MARKET/FINANCE/COMPLETED/CONFLICT',
  `requested_by` BIGINT UNSIGNED NOT NULL COMMENT '申请人',
  `requested_at` DATETIME(3) NOT NULL COMMENT '申请时间，UTC',
  `completed_at` DATETIME(3) NULL COMMENT '完成时间，UTC',
  `active_target` VARCHAR(160) NULL COMMENT '进行中目标唯一键，完成或冲突后清空',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，UTC',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_profile_change_request_1` (`tenant_id`,`active_target`),
  KEY `idx_profile_change_request_1` (`tenant_id`,`institution_id`,`status`,`current_step`),
  KEY `idx_profile_change_request_2` (`tenant_id`,`target_id`,`change_type`),
  CONSTRAINT `fk_profile_change_request_institution` FOREIGN KEY (`institution_id`) REFERENCES `crm_institution` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='机构资料与合同资质变更申请';

CREATE TABLE IF NOT EXISTS `crm_profile_change_step` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '企业/租户隔离',
  `change_request_id` BIGINT UNSIGNED NOT NULL COMMENT '变更申请',
  `sequence_no` INT NOT NULL COMMENT '历史顺序',
  `step_code` VARCHAR(32) NOT NULL COMMENT 'REQUESTED/MARKET/FINANCE/REVALIDATE/CONFLICT',
  `status` VARCHAR(48) NOT NULL COMMENT 'REQUESTED/APPROVED/REJECTED/CONFLICT_REVALIDATE',
  `reviewer_user_id` BIGINT UNSIGNED NOT NULL COMMENT '操作人',
  `reviewed_at` DATETIME(3) NOT NULL COMMENT '操作时间，UTC',
  `comment` VARCHAR(1000) NULL COMMENT '意见',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  PRIMARY KEY (`id`),
  KEY `idx_profile_change_step_1` (`tenant_id`,`change_request_id`,`sequence_no`,`id`),
  CONSTRAINT `fk_profile_change_step_request` FOREIGN KEY (`change_request_id`) REFERENCES `crm_profile_change_request` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='机构变更分级审批追加历史';
