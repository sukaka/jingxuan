CREATE TABLE IF NOT EXISTS `crm_ai_job` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL COMMENT '企业/租户隔离',
  `customer_id` BIGINT UNSIGNED NOT NULL COMMENT '由授权消息推导的客户',
  `conversation_id` VARCHAR(128) NOT NULL COMMENT '企微会话标识',
  `requested_by` BIGINT UNSIGNED NOT NULL COMMENT '任务创建人',
  `message_ids_json` JSON NOT NULL COMMENT '授权消息 ID 快照，不保存全文',
  `request_hash` CHAR(64) NOT NULL COMMENT '幂等请求 SHA-256',
  `idempotency_key` VARCHAR(128) NOT NULL COMMENT '客户端幂等键',
  `status` VARCHAR(32) NOT NULL COMMENT 'QUEUED/RUNNING/RETRY/PROPOSED/FAILED/CONFIRMED/REJECTED',
  `claimed_by` VARCHAR(64) NULL COMMENT '异步执行实例',
  `claimed_until` DATETIME(3) NULL COMMENT '执行占用截止时间',
  `attempt_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已执行次数',
  `next_retry_at` DATETIME(3) NULL COMMENT '下次可重试时间',
  `provider` VARCHAR(48) NULL COMMENT '实际模型供应商',
  `model_name` VARCHAR(128) NULL COMMENT '实际模型或 Mock 版本',
  `error_masked` VARCHAR(500) NULL COMMENT '脱敏错误，不含聊天和密钥',
  `confirmed_by` BIGINT UNSIGNED NULL COMMENT '人工确认人',
  `confirmed_at` DATETIME(3) NULL COMMENT '人工确认时间',
  `confirmation_reason` VARCHAR(1000) NULL COMMENT '人工确认或驳回原因',
  `confirmation_key` VARCHAR(128) NULL COMMENT '人工确认幂等键',
  `confirmation_hash` CHAR(64) NULL COMMENT '人工确认请求 SHA-256',
  `task_id` BIGINT UNSIGNED NULL COMMENT '人工确认生成的普通待办',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_ai_job_idempotency` (`tenant_id`,`requested_by`,`idempotency_key`),
  KEY `idx_ai_job_claim` (`tenant_id`,`status`,`next_retry_at`,`claimed_until`),
  KEY `idx_ai_job_conversation` (`tenant_id`,`conversation_id`,`id`),
  KEY `idx_ai_job_customer` (`tenant_id`,`customer_id`,`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='AI 证据抽取异步任务，不含聊天全文';

CREATE TABLE IF NOT EXISTS `crm_ai_insight` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL COMMENT '企业/租户隔离',
  `job_id` BIGINT UNSIGNED NOT NULL COMMENT 'AI 任务',
  `insight_type` VARCHAR(48) NOT NULL COMMENT '结构化意图类型',
  `project_codes_json` JSON NOT NULL COMMENT '授权项目编码列表',
  `mentioned_institution` VARCHAR(160) NULL COMMENT '聊天明确提及的机构名称',
  `mentioned_time` VARCHAR(128) NULL COMMENT '聊天原始时间表述',
  `absolute_time` DATETIME(3) NULL COMMENT '可靠归一化时间，无依据时为空',
  `evidence_message_ids_json` JSON NOT NULL COMMENT '属于输入的证据消息 ID',
  `confidence` DECIMAL(5,4) NOT NULL COMMENT '模型自报分数，不代表校准概率',
  `proposed_actions_json` JSON NOT NULL COMMENT '仅供人工选择的建议动作',
  `fact_status` VARCHAR(32) NOT NULL DEFAULT 'UNVERIFIED' COMMENT '始终待人工核实',
  `allow_financial_write` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '始终禁止资金写入',
  `reasoning_summary` VARCHAR(2000) NOT NULL COMMENT '简短证据摘要，不是思维链',
  `reply_draft` TEXT NULL COMMENT '人工可复制的话术草稿，不自动发送',
  `followup_draft_json` JSON NULL COMMENT '可编辑的回访待办草稿',
  `risk_flags_json` JSON NOT NULL COMMENT 'AI 风险建议标记，非处罚事实',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_ai_insight_job` (`tenant_id`,`job_id`),
  CONSTRAINT `fk_ai_insight_job` FOREIGN KEY (`job_id`) REFERENCES `crm_ai_job` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `chk_ai_insight_unverified` CHECK (`fact_status` = 'UNVERIFIED' AND `allow_financial_write` = 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='经 Schema 与证据校验的 AI 待核实建议';

