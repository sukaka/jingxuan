CREATE TABLE `crm_wecom_media_asset` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `tenant_id` BIGINT UNSIGNED NOT NULL COMMENT '租户隔离键',
  `message_id` BIGINT UNSIGNED NOT NULL COMMENT '已授权归档消息',
  `asset_index` INT UNSIGNED NOT NULL COMMENT '消息内媒体顺序',
  `sdk_file_id` TEXT NOT NULL COMMENT '企微官方媒体文件ID，不公开',
  `media_kind` VARCHAR(32) NOT NULL COMMENT 'image/voice/video/emotion/file/mixed等来源节点',
  `md5sum` VARCHAR(64) NULL COMMENT '企微提供的媒体MD5完整性校验值',
  `file_size` BIGINT UNSIGNED NULL COMMENT '企微声明的媒体字节数',
  `file_name` VARCHAR(255) NULL COMMENT '脱敏文件名或展示名',
  `content_type` VARCHAR(128) NOT NULL DEFAULT 'application/octet-stream' COMMENT '媒体MIME类型',
  `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/DOWNLOADING/RETRY/STORED/FAILED',
  `object_key` VARCHAR(512) NULL COMMENT '私有对象存储Key，不公开',
  `content_sha256` CHAR(64) NULL COMMENT '实际下载内容SHA256',
  `actual_size` BIGINT UNSIGNED NULL COMMENT '实际下载字节数',
  `error_masked` VARCHAR(500) NULL COMMENT '脱敏后的最近错误',
  `attempt_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已领取下载次数',
  `next_retry_at` DATETIME(3) NULL COMMENT '下次允许重试时间UTC',
  `lease_owner` VARCHAR(64) NULL COMMENT 'Worker租约所有者',
  `lease_until` DATETIME(3) NULL COMMENT 'Worker租约到期UTC',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间UTC',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_wecom_media_message_index` (`tenant_id`,`message_id`,`asset_index`),
  KEY `idx_wecom_media_claim` (`tenant_id`,`status`,`next_retry_at`,`lease_until`),
  KEY `idx_wecom_media_message` (`tenant_id`,`message_id`,`status`),
  CONSTRAINT `fk_wecom_media_message` FOREIGN KEY (`message_id`) REFERENCES `crm_wecom_message` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='企微媒体元数据与下载状态，大二进制仅在私有对象存储';
